-- Cambio formal aprobado: conexiones entre líneas, separadas de sus tramos.
-- No convierte ni reinterpreta diseños históricos.
BEGIN;
CREATE TABLE IF NOT EXISTS conexion_lineas (
    id_conexion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_diseno INTEGER NOT NULL,
    linea_a VARCHAR(100) NOT NULL,
    estacion_a VARCHAR(100) NOT NULL,
    linea_b VARCHAR(100) NOT NULL,
    estacion_b VARCHAR(100) NOT NULL,
    CONSTRAINT chk_conexion_lineas_distintas CHECK (linea_a <> linea_b),
    CONSTRAINT uq_conexion_lineas UNIQUE (id_diseno, linea_a, estacion_a, linea_b, estacion_b),
    CONSTRAINT fk_conexion_origen FOREIGN KEY (id_diseno, linea_a, estacion_a)
        REFERENCES pasa(id_diseno, nombre_linea, nombre_estacion) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_conexion_destino FOREIGN KEY (id_diseno, linea_b, estacion_b)
        REFERENCES pasa(id_diseno, nombre_linea, nombre_estacion) ON UPDATE CASCADE ON DELETE CASCADE
);
GRANT SELECT, INSERT, UPDATE, DELETE ON conexion_lineas TO metronet_app;
GRANT USAGE, SELECT ON SEQUENCE conexion_lineas_id_conexion_seq TO metronet_app;
COMMIT;
