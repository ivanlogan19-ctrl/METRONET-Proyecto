    private void red(int diseno) {
        var palacio = geografia.resolverPunto(1, null);
        var rambla = geografia.resolverPunto(26, null);
        jdbc.update("INSERT INTO estacion VALUES (?,'A',?,?,FALSE)", diseno, geografia.posicionX(palacio), geografia.posicionY(palacio));
        jdbc.update("INSERT INTO estacion VALUES (?,'B',700,480,FALSE)", diseno);
        jdbc.update("INSERT INTO estacion VALUES (?,'C',?,?,FALSE)", diseno, geografia.posicionX(rambla), geografia.posicionY(rambla));
        jdbc.update("INSERT INTO linea VALUES (?,'Azul')", diseno);
        jdbc.update("INSERT INTO tramo VALUES (?,'Azul','A','B'),(?,'Azul','B','C')", diseno, diseno);
        for (String nombre : new String[]{"A", "B", "C"}) jdbc.update("INSERT INTO pasa VALUES (?,'Azul',?)", diseno, nombre);
        jdbc.update("INSERT INTO metro(id_diseno,nombre_linea) VALUES (?,'Azul')", diseno);
    }

    private void simular(int diseno) {
        jdbc.update("INSERT INTO simulacion(id_intento,comentarios) VALUES (?,?)", diseno, juego.marcaRedSimulada(diseno));
    }

    private ConsignaDisenoResponse consigna() { return juego.obtenerConsigna(usuario, 4); }
    private void reglas(String json) { jdbc.update("UPDATE escenario SET reglas_exito=? WHERE numero=4", json); }

    private void redAvanzada(int diseno, int nivel) throws Exception {
        var reglas = mapper.readTree(jdbc.queryForObject("SELECT reglas_exito FROM escenario WHERE numero=?", String.class, nivel));
        int cantidad = reglas.path("minimoEstaciones").asInt();
        int indice = 0;
        for (var objetivo : reglas.path("puntosInteresObjetivo")) {
            var poi = geografia.resolverPunto(objetivo.path("idPunto").asInt(), null);
            jdbc.update("INSERT INTO estacion VALUES (?,?,?,?,?)", diseno, "E" + indice++,
                RestriccionesGeograficasService.redondear(geografia.posicionX(poi)),
                RestriccionesGeograficasService.redondear(geografia.posicionY(poi)), false);
        }
        while (indice < cantidad) {
            jdbc.update("INSERT INTO estacion VALUES (?,?,?,?,FALSE)", diseno, "E" + indice, 660 + indice * 5, 460);
            indice++;
        }
        jdbc.update("INSERT INTO linea VALUES (?,'Principal')", diseno);
        jdbc.update("INSERT INTO metro(id_diseno,nombre_linea,velocidad_promedio) VALUES (?,'Principal',?)", diseno, 4);
        for (int i = 0; i < cantidad; i++) {
            jdbc.update("INSERT INTO pasa VALUES (?,'Principal',?)", diseno, "E" + i);
            if (i > 0) jdbc.update("INSERT INTO tramo VALUES (?,'Principal',?,?)", diseno, "E" + (i - 1), "E" + i);
        }
        int intercambios = reglas.path("minimoTransbordos").asInt();
        for (int i = 1; i < reglas.path("minimoLineas").asInt(); i++) {
            String linea = "Enlace" + i;
            String origen = "E" + (nivel == 10 ? i - 1 : 0);
            String destino = "E2";
            jdbc.update("INSERT INTO linea VALUES (?,?)", diseno, linea);
            jdbc.update("INSERT INTO metro(id_diseno,nombre_linea,velocidad_promedio) VALUES (?,?,?)", diseno, linea, 4);
            jdbc.update("INSERT INTO pasa VALUES (?,?,?),(?,?,?)", diseno, linea, origen, diseno, linea, destino);
            jdbc.update("INSERT INTO tramo VALUES (?,?,?,?)", diseno, linea, origen, destino);
        }
        for (int i = 0; i < intercambios; i++) {
            String nombre = "E" + (intercambios == 2 && i == 1 ? 2 : i);
            jdbc.update("UPDATE estacion SET transbordo=TRUE WHERE id_diseno=? AND nombre=?", diseno, nombre);
        }
    }

    @Test
    void administradorAccedeATodosLosNivelesYLibreSinPuntosAutomaticos() {
        jdbc.update("UPDATE usuario SET rol='ADMIN' WHERE id_usuario=7");
        jdbc.update("INSERT INTO escenario VALUES (11,NULL,'Libre','','','', 'EDICION_LIBRE',TRUE,'{}','{}')");
        jdbc.update("INSERT INTO intento VALUES (10,7,10,10,1,'EN_DESARROLLO',0,NULL,NULL)");
        jdbc.update("INSERT INTO intento VALUES (11,7,11,11,1,'EN_DESARROLLO',0,NULL,NULL)");
        var progreso = juego.obtenerResumenProgreso(7);
        assertTrue(progreso.escenarios().stream().allMatch(e -> e.desbloqueado()));
        assertTrue(progreso.modoLibreDesbloqueado());
        assertEquals(0, progreso.nivelesCompletados());
        assertEquals("EN_DESARROLLO", juego.iniciarEscenario(7, 10).estado());
        assertEquals(11, juego.iniciarEscenario(7, 11).idDiseno());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM intento WHERE puntaje IS NOT NULL", Integer.class));
        jdbc.update("UPDATE usuario SET rol='JUGADOR' WHERE id_usuario=7");
        assertThrows(ResponseStatusException.class, () -> juego.iniciarEscenario(7, 10));
        assertFalse(juego.tieneModoLibreDesbloqueado(7));
    }

    @Test
    void comparacionesRequierenEjecucionesRealesYSinOptimoFisico() throws Exception {
        jdbc.update("INSERT INTO intento VALUES (6,7,6,6,1,'EN_DESARROLLO',0,NULL,NULL)");
        redAvanzada(6, 6);
        simular(6);
        assertFalse(juego.evaluarEscenario(7, 6).completado(), "Play solo no completa la práctica");
        jdbc.update("UPDATE metro SET velocidad_promedio=6 WHERE id_diseno=6");
        assertFalse(juego.evaluarEscenario(7, 6).completado(), "Un cambio sin ejecutar no basta");
        simular(6);
        assertFalse(juego.evaluarEscenario(7, 6).completado(), "Aún falta comparar horas");
        ComparacionesSimulacionFixture.registrar(jdbc, juego, 6, 8);
        var completo = juego.evaluarEscenario(7, 6);
        assertTrue(completo.completado()); assertEquals(100, completo.puntaje());
        assertEquals(6, completo.desempeno().unidades().getFirst().velocidad());
        assertTrue(completo.desempeno().unidades().getFirst().tramos() > 0);
        jdbc.update("UPDATE metro SET velocidad_promedio=7 WHERE id_diseno=6");
        assertFalse(juego.evaluarEscenario(7, 6).completado(), "La ejecución ya no refleja las UV actuales");
        ComparacionesSimulacionFixture.registrar(jdbc, juego, 6, 8);
        assertTrue(juego.evaluarEscenario(7, 6).completado());
        assertEquals(100, jdbc.queryForObject("SELECT puntaje FROM intento WHERE id_intento=6", Integer.class));
        jdbc.update("UPDATE estacion SET posicion_x=0,posicion_y=0 WHERE id_diseno=6 AND nombre='E0'");
        assertFalse(juego.evaluarEscenario(7, 6).completado());
    }

    @Test
    void cambiosIndividualesGlobalesYHorasSeDistinguenSinPromedios() throws Exception {
        jdbc.update("INSERT INTO intento VALUES (8,7,8,8,1,'EN_DESARROLLO',0,NULL,NULL)");
        redAvanzada(8, 8);
        simular(8); simular(8);
        assertFalse(juego.evaluarEscenario(7, 8).completado(), "Repetir Play no constituye comparación");
        jdbc.update("UPDATE metro SET velocidad_promedio=5 WHERE id_diseno=8");
        assertFalse(juego.obtenerConsigna(usuario, 8).condiciones().stream().filter(c -> c.clave().endsWith(":global")).findFirst().orElseThrow().completado());
        simular(8);
        var condiciones = juego.obtenerConsigna(usuario, 8).condiciones();
        assertTrue(condiciones.stream().filter(c -> c.clave().endsWith(":global")).findFirst().orElseThrow().completado());
        assertFalse(condiciones.stream().filter(c -> c.clave().endsWith(":individual")).findFirst().orElseThrow().completado());
        jdbc.update("UPDATE metro SET velocidad_promedio=2 WHERE id_diseno=8 AND id_tren=(SELECT MIN(id_tren) FROM metro WHERE id_diseno=8)");
        simular(8);
        assertTrue(juego.evaluarEscenario(7, 8).completado());
        assertEquals(2, juego.obtenerDesempeno(7, 8).unidades().stream().map(u -> u.velocidad()).distinct().count());
    }

