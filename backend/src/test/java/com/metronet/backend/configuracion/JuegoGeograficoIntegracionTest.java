    @Test
    void cuatroNivelesConservanHerramientasYProgresionYPersistenIntentos() throws Exception {
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> juego.iniciarEscenario(7, 2)).getStatusCode().value());
        for (int nivel = 1; nivel <= 4; nivel++) {
            assertFalse(juego.evaluarEscenario(7, nivel).completado());
            red(nivel);
            if (nivel < 4) {
                assertTrue(juego.obtenerConsigna(usuario, nivel).referenciasObjetivo().isEmpty());
                var herramientas = mapper.readTree(jdbc.queryForObject("SELECT herramientas_habilitadas FROM escenario WHERE numero=?", String.class, nivel));
                assertFalse(herramientas.path("simulacion").asBoolean());
                assertEquals(nivel >= 2, herramientas.path("conexiones").asBoolean());
                assertEquals(nivel >= 3, herramientas.path("metros").asBoolean());
            } else {
                assertFalse(juego.evaluarEscenario(7, 4).completado());
                assertEquals(2, consigna().referenciasObjetivo().size());
                ComparacionesSimulacionFixture.practicar(jdbc, juego, 4);
            }
            var resultado = juego.evaluarEscenario(7, nivel);
            assertTrue(resultado.completado(), "Nivel " + nivel);
            assertEquals(100, resultado.progreso());
            assertEquals("COMPLETADO", jdbc.queryForObject("SELECT estado FROM intento WHERE id_intento=?", String.class, nivel));
            assertNotNull(jdbc.queryForObject("SELECT fecha_finalizacion FROM intento WHERE id_intento=?", java.sql.Timestamp.class, nivel));
            if (nivel < 4) assertEquals(nivel + 1, juego.iniciarEscenario(7, nivel + 1).idDiseno());
        }
        assertFalse(jdbc.queryForObject("SELECT campana_completada_historicamente FROM usuario", Boolean.class));
        assertEquals(5, juego.evaluarEscenario(7, 4).idSiguienteEscenario());
        var reiniciado = juego.reiniciarRecorrido(7, 1);
        assertEquals(2, reiniciado.numeroCampanaActual());
        assertEquals(0, reiniciado.nivelesCompletados());
        assertEquals(4, jdbc.queryForObject("SELECT COUNT(*) FROM intento WHERE estado='COMPLETADO'", Integer.class));
        assertEquals(409, assertThrows(ResponseStatusException.class, () -> juego.evaluarEscenario(7, 4)).getStatusCode().value());
    }

