    @Test
    void diezNivelesTienenSolucionConGeografiaRealYProgresoPersistido() throws Exception {
        for (int nivel = 1; nivel <= 10; nivel++) {
            if (nivel > 4) jdbc.update("INSERT INTO intento VALUES (?,?,?, ?,1,'EN_DESARROLLO',0,NULL,NULL)", nivel, 7, nivel, nivel);
            assertFalse(juego.evaluarEscenario(7, nivel).completado(), "Una red vacía no resuelve " + nivel);
            if (nivel <= 4) red(nivel); else redAvanzada(nivel, nivel);
            if (nivel >= 4) ComparacionesSimulacionFixture.practicar(jdbc, juego, nivel);
            var consigna = juego.obtenerConsigna(usuario, nivel);
            assertTrue(consigna.condiciones().stream().allMatch(c -> c.completado()), "Nivel " + nivel + ": " + consigna.condiciones());
            var resultado = juego.evaluarEscenario(7, nivel);
            assertTrue(resultado.completado());
            assertEquals(100, resultado.puntaje());
            assertEquals(100, resultado.desempeno().puntaje());
            assertEquals(nivel == 10 ? null : nivel + 1, resultado.idSiguienteEscenario());
            var resumen = juego.obtenerResumenProgreso(7);
            assertEquals(10, resumen.cantidadNiveles());
            assertEquals(nivel, resumen.nivelesCompletados());
            assertEquals(nivel == 10, resumen.campanaCompletada());
            assertEquals(nivel == 10, resumen.modoLibreDesbloqueado());
            if (nivel < 10) assertTrue(resumen.escenarios().get(nivel).desbloqueado());
            if (nivel < 9) assertFalse(resumen.escenarios().get(nivel + 1).desbloqueado());
        }
        assertEquals(409, assertThrows(ResponseStatusException.class, () -> juego.iniciarEscenario(7, 10)).getStatusCode().value());
        var reinicio = juego.reiniciarRecorrido(7, 1);
        assertEquals(0, reinicio.nivelesCompletados());
        assertEquals(2, reinicio.numeroCampanaActual());
        assertTrue(reinicio.modoLibreDesbloqueado());
        assertEquals(10, jdbc.queryForObject("SELECT COUNT(*) FROM intento WHERE estado='COMPLETADO'", Integer.class));
        assertFalse(reinicio.escenarios().get(9).desbloqueado());
    }

    @Test
    void cadaNuevoNivelRechazaUnaRedQueResuelveElAnteriorYElLimiteEsReal() throws Exception {
        for (int nivel = 5; nivel <= 10; nivel++) {
            jdbc.update("INSERT INTO intento VALUES (?,?,?, ?,1,'EN_DESARROLLO',0,NULL,NULL)", nivel, 7, nivel, nivel);
            if (nivel == 5) red(nivel); else redAvanzada(nivel, nivel - 1);
            simular(nivel);
            if (nivel == 9) {
                // Conservar los conteos del nivel 8, pero alejar 15 unidades una estación de su POI.
                jdbc.update("UPDATE estacion SET posicion_y=posicion_y-15 WHERE id_diseno=9 AND nombre='E2'");
            }
            assertFalse(juego.obtenerConsigna(usuario, nivel).condiciones().stream().allMatch(c -> c.completado()), "La red anterior no debe bastar para " + nivel);
        }
        jdbc.update("INSERT INTO estacion VALUES (9,'ExtraA',700,460,FALSE),(9,'ExtraB',710,460,FALSE)");
        assertFalse(juego.obtenerConsigna(usuario, 9).condiciones().stream()
            .filter(c -> c.clave().equals("maximoEstaciones")).findFirst().orElseThrow().completado());
    }

